"""Minimal SVG writer for the same geometry the DXF writer emits.

Standard library only. Writes closed polylines and circles in
millimetres (SVG user units = mm here, via the viewBox), so the file
opens at the right size in Inkscape, LightBurn and any browser, with
no conversion step. A laser cuts the stroke path; the stroke width
is only a display setting and does not change the cut.
"""

from __future__ import annotations


def _fmt(value: float) -> str:
    """Format a coordinate with 3 decimals, avoiding -0.000."""
    if abs(value) < 0.0005:
        value = 0.0
    return f"{value:.3f}"


class SvgDocument:
    """An SVG document: polylines + circles only.

    Mirrors DxfDocument's API so the CLI can emit either format from
    the same geometry.
    """

    def __init__(self) -> None:
        self._polylines: list[list[tuple[float, float]]] = []
        self._circles: list[tuple[float, float, float]] = []

    def add_polyline(self, points: list[tuple[float, float]]) -> None:
        """Add a closed polyline. Needs at least 3 points."""
        if len(points) < 3:
            raise ValueError("a polyline needs at least 3 points")
        self._polylines.append([(float(x), float(y)) for x, y in points])

    def add_circle(self, cx: float, cy: float, radius: float) -> None:
        """Add a circle element."""
        if radius <= 0:
            raise ValueError("circle radius must be positive")
        self._circles.append((float(cx), float(cy), float(radius)))

    @property
    def entity_count(self) -> int:
        return len(self._polylines) + len(self._circles)

    def bounds(self) -> tuple[float, float, float, float]:
        """(min_x, min_y, max_x, max_y) over all entities."""
        xs: list[float] = []
        ys: list[float] = []
        for pts in self._polylines:
            for x, y in pts:
                xs.append(x)
                ys.append(y)
        for cx, cy, r in self._circles:
            xs.extend([cx - r, cx + r])
            ys.extend([cy - r, cy + r])
        if not xs:
            return (0.0, 0.0, 0.0, 0.0)
        return (min(xs), min(ys), max(xs), max(ys))

    def to_string(self) -> str:
        # SVG's y axis points down; DXF's points up. Flip y so the
        # file looks exactly like the DXF does in a CAD viewer,
        # instead of a vertical mirror image of it.
        polys = [[(x, -y) for x, y in pts] for pts in self._polylines]
        circles = [(cx, -cy, r) for cx, cy, r in self._circles]
        xs = [x for pts in polys for x, _ in pts]
        ys = [y for pts in polys for _, y in pts]
        for cx, cy, r in circles:
            xs.extend([cx - r, cx + r])
            ys.extend([cy - r, cy + r])
        if xs:
            min_x, min_y, max_x, max_y = (min(xs), min(ys),
                                          max(xs), max(ys))
        else:
            min_x, min_y, max_x, max_y = (0.0, 0.0, 0.0, 0.0)
        width = max_x - min_x
        height = max_y - min_y
        lines = [
            '<?xml version="1.0" encoding="UTF-8"?>',
            "<!-- Generated by LaserCut DXF Generator: "
            "all units are millimetres. -->",
            f'<svg xmlns="http://www.w3.org/2000/svg" '
            f'width="{_fmt(width)}mm" height="{_fmt(height)}mm" '
            f'viewBox="{_fmt(min_x)} {_fmt(min_y)} '
            f'{_fmt(width)} {_fmt(height)}">',
            '  <g fill="none" stroke="#000000" stroke-width="0.1">',
        ]
        for pts in polys:
            points = " ".join(f"{_fmt(x)},{_fmt(y)}" for x, y in pts)
            lines.append(f'    <polygon points="{points}" />')
        for cx, cy, r in circles:
            lines.append(
                f'    <circle cx="{_fmt(cx)}" cy="{_fmt(cy)}" '
                f'r="{_fmt(r)}" />')
        lines.append("  </g>")
        lines.append("</svg>")
        return "\n".join(lines) + "\n"

    def write(self, path: str) -> None:
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(self.to_string())


__all__ = ["SvgDocument"]
